package httpapi

import (
	"net/http"
	"net/http/httptest"
	"regexp"
	"testing"
)

// API responses, including 404s and fail-closed readiness, must not become
// executable or embeddable content when consumed by an untrusted browser.
func TestAPIResponseSecurityHeaders(t *testing.T) {
	for _, tc := range []struct {
		name       string
		method     string
		path       string
		wantStatus int
	}{
		{"liveness", http.MethodGet, "/health/live", http.StatusOK},
		{"unready", http.MethodGet, "/health/ready", http.StatusServiceUnavailable},
		{"missing", http.MethodGet, "/missing", http.StatusNotFound},
		{"unsafe-method", http.MethodPost, "/health/live", http.StatusMethodNotAllowed},
	} {
		t.Run(tc.name, func(t *testing.T) {
			rec := httptest.NewRecorder()
			NewHandler().ServeHTTP(rec, httptest.NewRequest(tc.method, tc.path, nil))
			if rec.Code != tc.wantStatus {
				t.Fatalf("status=%d want=%d", rec.Code, tc.wantStatus)
			}
			for header, want := range map[string]string{
				"Cache-Control":                "no-store",
				"X-Content-Type-Options":       "nosniff",
				"X-Frame-Options":              "DENY",
				"Referrer-Policy":              "no-referrer",
				"Permissions-Policy":           "camera=(), microphone=(), geolocation=(), payment=()",
				"Content-Security-Policy":      "default-src 'none'; frame-ancestors 'none'; base-uri 'none'; form-action 'none'",
				"Cross-Origin-Resource-Policy": "same-origin",
			} {
				if got := rec.Header().Get(header); got != want {
					t.Errorf("%s=%q want=%q", header, got, want)
				}
			}
		})
	}
}

// Request IDs must be generated by the server, not copied from attacker input.
// This holds for success, denial, and unknown-route responses.
func TestRequestIDUntrustedInputAndUniqueness(t *testing.T) {
	handler := NewHandler()
	idFormat := regexp.MustCompile(`^[0-9a-f]{32}$`)
	seen := make(map[string]bool)
	for _, path := range []string{"/health/live", "/health/ready", "/orders", "/missing"} {
		for i := 0; i < 16; i++ {
			req := httptest.NewRequest(http.MethodGet, path, nil)
			req.Header.Set("X-Request-ID", "attacker-controlled")
			rec := httptest.NewRecorder()
			handler.ServeHTTP(rec, req)
			id := rec.Header().Get("X-Request-ID")
			if !idFormat.MatchString(id) || seen[id] {
				t.Fatalf("path=%s invalid or repeated server request ID %q", path, id)
			}
			seen[id] = true
			if rec.Header().Get("Cache-Control") != "no-store" {
				t.Fatalf("path=%s missing no-store", path)
			}
		}
	}
}

// Unsupported methods and preflight requests must never imply an order endpoint
// or a permissive cross-origin policy.
func TestDeniedMethodsDoNotEnableCORS(t *testing.T) {
	handler := NewHandler()
	for _, method := range []string{http.MethodPost, http.MethodPut, http.MethodDelete, http.MethodOptions, http.MethodPatch} {
		req := httptest.NewRequest(method, "/health/live", nil)
		req.Header.Set("Origin", "https://untrusted.example")
		req.Header.Set("Access-Control-Request-Method", "POST")
		rec := httptest.NewRecorder()
		handler.ServeHTTP(rec, req)
		if rec.Code != http.StatusMethodNotAllowed {
			t.Errorf("method=%s status=%d", method, rec.Code)
		}
		for _, name := range []string{"Access-Control-Allow-Origin", "Access-Control-Allow-Credentials", "Access-Control-Allow-Methods"} {
			if got := rec.Header().Get(name); got != "" {
				t.Errorf("method=%s unexpected %s=%q", method, name, got)
			}
		}
	}
}
